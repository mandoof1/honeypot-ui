#!/usr/bin/env bash
#
# Regenerate the hashed lock files the images install from.
#
#   bash scripts/lock-requirements.sh           # rewrite both lock files
#   bash scripts/lock-requirements.sh --check   # exit 1 if a lock is stale
#
# backend/requirements.txt and honeypot/requirements.txt stay the files people
# edit: direct dependencies, pinned by version. The images install from
# requirements.lock beside each, which adds every transitive dependency and
# the SHA-256 of every file pip may download, and pip is run with
# --require-hashes, so a package that changes on the index after the lock was
# written fails the build instead of entering the image.
#
# Run this after any change to a requirements.txt and commit the result. The
# image build checks the two files agree and stops if they do not.
#
# Needs uv (https://docs.astral.sh/uv/) or pip-tools.

set -euo pipefail
cd "$(dirname "$0")/.."

PYTHON_VERSION=3.12        # the images' interpreter
TARGETS=(backend honeypot)

check() {
  python3 - "${TARGETS[@]}" <<'PY'
import pathlib, re, sys

PIN = re.compile(r"^([A-Za-z0-9_.-]+)(?:\[[^\]]*\])?==([^\s;\\]+)")
norm = lambda name: re.sub(r"[-_.]+", "-", name).lower()
stale = False
for target in sys.argv[1:]:
    wanted, locked = {}, {}
    for line in pathlib.Path(target, "requirements.txt").read_text().splitlines():
        match = PIN.match(line.strip())
        if match:
            wanted[norm(match[1])] = match[2]
    lock = pathlib.Path(target, "requirements.lock")
    if not lock.exists():
        print(f"{lock}: missing")
        stale = True
        continue
    for line in lock.read_text().splitlines():
        match = PIN.match(line.strip())
        if match:
            locked[norm(match[1])] = match[2]
    for name, version in sorted(wanted.items()):
        if locked.get(name) != version:
            print(f"{lock}: has {name}=={locked.get(name)}, requirements.txt wants {version}")
            stale = True
if stale:
    print("Run: bash scripts/lock-requirements.sh")
sys.exit(1 if stale else 0)
PY
}

if [[ "${1:-}" == --check ]]; then
  check
  exit
fi

for target in "${TARGETS[@]}"; do
  if command -v uv >/dev/null 2>&1; then
    # --universal: one lock for x86-64 and arm64, with markers where a
    # dependency is platform-specific.
    uv pip compile "$target/requirements.txt" --generate-hashes --universal \
      --python-version "$PYTHON_VERSION" --no-header --quiet \
      -o "$target/requirements.lock"
  elif command -v pip-compile >/dev/null 2>&1; then
    pip-compile --generate-hashes --allow-unsafe --no-header --quiet \
      -o "$target/requirements.lock" "$target/requirements.txt"
  else
    echo "Neither uv nor pip-compile is installed." >&2
    exit 1
  fi
  # A fixed first line instead of the tool's header, which embeds the
  # command line and would differ between the two tools.
  { printf '# Generated by scripts/lock-requirements.sh from %s/requirements.txt. Do not edit.\n' "$target"
    cat "$target/requirements.lock"; } > "$target/requirements.lock.tmp"
  mv "$target/requirements.lock.tmp" "$target/requirements.lock"
  echo "wrote $target/requirements.lock ($(grep -c '^[A-Za-z0-9]' "$target/requirements.lock") packages)"
done
check
